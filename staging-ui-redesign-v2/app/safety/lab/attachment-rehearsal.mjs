// Isolated synthetic object rehearsal. Never deletes/overwrites buckets or objects.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { createHash, randomUUID } from 'node:crypto';
const lab = '/private/tmp/marginflow-safety-lab';
const { createClient } = createRequire(`${lab}/app/package.json`)('@supabase/supabase-js');
const keys = JSON.parse(readFileSync(`${lab}/local-status.json`, 'utf8'));
if (keys.API_URL !== 'http://127.0.0.1:55431') throw new Error('Refusing non-lab target');
const client = createClient(keys.API_URL, keys.SERVICE_ROLE_KEY, { auth: { persistSession: false } });
const checked = async p => { const result = await p; if (result.error) throw result.error; return result.data; };
const suffix = randomUUID();
const source = `safety-source-${suffix}`, restored = `safety-restored-${suffix}`;
const path = 'fictional-invoice.txt';
const bytes = Buffer.from('FICTIONAL attachment — Safety Lab — GBP 15.00\n');
const sha256 = b => createHash('sha256').update(b).digest('hex');
await checked(client.storage.createBucket(source, { public: false }));
await checked(client.storage.from(source).upload(path, bytes, { contentType: 'text/plain', upsert: false }));
const downloaded = Buffer.from(await (await checked(client.storage.from(source).download(path))).arrayBuffer());
mkdirSync(`${lab}/backup`, { recursive: true, mode: 0o700 });
const backupPath = `${lab}/backup/${suffix}.txt`;
writeFileSync(backupPath, downloaded, { mode: 0o600 });
await checked(client.storage.createBucket(restored, { public: false }));
await checked(client.storage.from(restored).upload(path, readFileSync(backupPath), { contentType: 'text/plain', upsert: false }));
const verified = Buffer.from(await (await checked(client.storage.from(restored).download(path))).arrayBuffer());
if (sha256(bytes) !== sha256(verified)) throw new Error('Restored attachment differs');
const evidence = { scope: 'one fictional object, not application linkage or production backup', source, restored, path, bytes: bytes.length, sha256: sha256(bytes), result: 'PASS' };
writeFileSync(`${lab}/backup/attachment-result.json`, JSON.stringify(evidence, null, 2), { mode: 0o600 });
console.log(JSON.stringify(evidence));
